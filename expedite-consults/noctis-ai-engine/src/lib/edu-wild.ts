import { FACE, type FeedPost, type Teach } from "@/lib/feed-data";

const yt = (id: string) => ({
  mediaType: "video" as const,
  mediaUrl: `https://www.youtube.com/watch?v=${id}`,
  posterUrl: `https://i.ytimg.com/vi/${id}/hqdefault.jpg`,
  youtubeId: id,
});

const teach = (hook: string, stamp: string, prompt: string, ok: string, wrong: [string, string]): Teach => ({
  hook,
  stamp,
  prompt,
  options: [
    { id: "a", label: ok, ok: true },
    { id: "b", label: wrong[0], ok: false },
    { id: "c", label: wrong[1], ok: false },
  ],
});

function clip(
  id: string,
  author: FeedPost["author"],
  caption: string,
  youtubeId: string,
  views: number,
  likes: number,
  hashtags: string[],
  house: string,
  lesson: Teach,
): FeedPost {
  return {
    id,
    author,
    caption,
    lane: "learn",
    ...yt(youtubeId),
    views,
    likes,
    comments: Math.round(likes / 28),
    shares: Math.round(likes / 8),
    isLiked: false,
    isSaved: false,
    isFollowing: true,
    hashtags,
    musicTitle: `ConnectLn · ${house}`,
    teach: lesson,
  };
}

