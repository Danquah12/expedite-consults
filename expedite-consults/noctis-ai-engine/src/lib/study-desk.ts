export function studyHouseOf(post: FeedPost): StudyHouse | undefined {
  if (STUDY_HOUSE_OF[post.id]) return STUDY_HOUSE_OF[post.id];
  const tags = post.hashtags.map((t) => t.replace("#", "").toLowerCase());
  const named: StudyHouse[] = ["jhu", "nih", "cdc", "hhmi", "nature", "cern", "yale", "nist", "space", "loc", "cyber", "fauna", "practice", "carpentry", "auto", "law", "it", "rmf", "attack", "linux", "offense", "vuln"];
  for (const id of named) {
    if (tags.includes(id)) return id;
  }
  return undefined;
}

export function studyDeck(posts: FeedPost[], houseId: StudyHouse | "all", seed?: number, waveIds: string[] = [], priorIds: string[] = [], watch?: DayWatch) {
  const ours = posts.filter((p) => {
    const house = studyHouseOf(p);
    if (!house || isAiClip(p)) return false;
    if (houseId === "all" && (house === "path" || house === "sci" || house === "eng")) return false;
    return true;
  });
  if (houseId === "career" || houseId === "tools" || houseId === "pentest" || houseId === "news" || houseId === "path" || houseId === "sci" || houseId === "eng" || houseId === "circle") return [];
  const salt = seed ?? visitorSeed("study");
  const pool = houseId === "all" ? ours : ours.filter((p) => studyHouseOf(p) === houseId);
  return dealReels(pool, salt, null, waveIds, priorIds, watch);
}
