function clip(
  id: string,
  author: FeedPost["author"],
  title: string,
  origin: string,
  youtubeId: string,
  views: number,
  likes: number,
  tags: string[],
  lesson: Teach,
): FeedPost {
  return {
    id,
    author,
    caption: `${title}. Original · ${origin}. Presented by ${SOURCE}.`,
    lane: "learn",
    ...yt(youtubeId),
    views,
    likes,
    comments: Math.round(likes / 24),
    shares: Math.round(likes / 10),
    isLiked: false,
    isSaved: false,
    isFollowing: true,
    hashtags: tags,
    musicTitle: `${origin} · ${SOURCE}`,
    teach: lesson,
  };
}

