import { type FeedPost, type Teach } from "@/lib/feed-data";
import { SOURCE } from "@/lib/source";

const yt = (id: string) => ({
  mediaType: "video" as const,
  mediaUrl: `https://www.youtube.com/watch?v=${id}`,
  posterUrl: `https://i.ytimg.com/vi/${id}/hqdefault.jpg`,
  youtubeId: id,
});

const face = (name: string) =>
  `https://ui-avatars.com/api/?name=${encodeURIComponent(name)}&background=0b1220&color=e4b86a&size=128&bold=true`;

const who = (name: string, username: string) => ({ name, username, avatar: face(name) });

const teach = (hook: string, stamp: string, prompt: string, ok: string, wrong: [string, string]): Teach => ({
  hook,
  stamp,
  prompt,
  options: [
    { id: "a", label: ok, ok: true },
    { id: "b", label: wrong[0], ok: false },
    { id: "c", label: wrong[1], ok: false },
  ],
});

function clip(
  id: string,
  author: FeedPost["author"],
  title: string,
  origin: string,
  youtubeId: string,
  views: number,
  likes: number,
  tags: string[],
  lesson: Teach,
): FeedPost {
  return {
    id,
    author,
    caption: `${title}. For the shelf. Original · ${origin}. Presented by ${SOURCE}.`,
    lane: "learn",
    ...yt(youtubeId),
    views,
    likes,
    comments: Math.max(1, Math.round(likes / 30)),
    shares: Math.max(1, Math.round(likes / 12)),
    isLiked: false,
    isSaved: false,
    isFollowing: true,
    hashtags: tags,
    musicTitle: `${origin} · ${SOURCE}`,
    teach: lesson,
  };
}

